const fs = require("fs");
const os = require("os");
const path = require("path");
const { spawnSync } = require("child_process");

const { timestampForPath } = require("./generate-delivery-evidence");
const { buildGitState } = require("./generate-final-status-report");

const root = path.join(__dirname, "..", "..", "..");
const npmCommand = process.platform === "win32" ? "npm.cmd" : "npm";
const DEFAULT_TIMEOUT_MS = 1200000;

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function argValue(name, fallback) {
  const prefix = `--${name}=`;
  const match = process.argv.find((arg) => arg.startsWith(prefix));
  return match ? match.slice(prefix.length) : fallback;
}

function hasFlag(name) {
  return process.argv.includes(`--${name}`);
}

function runCommand(label, args, timeoutMs = DEFAULT_TIMEOUT_MS) {
  const startedAt = new Date();
  const result = spawnSync(npmCommand, args, {
    cwd: root,
    encoding: "utf8",
    shell: process.platform === "win32",
    timeout: timeoutMs,
  });
  const timedOut = result.error?.code === "ETIMEDOUT";
  if (timedOut && process.platform === "win32" && result.pid) {
    spawnSync("taskkill", ["/PID", String(result.pid), "/T", "/F"], { encoding: "utf8" });
  }
  return {
    label,
    command: [npmCommand, ...args].join(" "),
    startedAt: startedAt.toISOString(),
    finishedAt: new Date().toISOString(),
    exitCode: timedOut ? 124 : result.status ?? (result.error ? 1 : 0),
    timeoutMs,
    timedOut,
    stdout: result.stdout || "",
    stderr: result.stderr || "",
    error: result.error?.message || null,
  };
}

function writeCommandLog(dir, item) {
  const fileName = `${item.label.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "command"}.log`;
  fs.writeFileSync(
    path.join(dir, fileName),
    [
      `# ${item.label}`,
      `command=${item.command}`,
      `startedAt=${item.startedAt}`,
      `finishedAt=${item.finishedAt}`,
      `exitCode=${item.exitCode}`,
      `timeoutMs=${item.timeoutMs}`,
      `timedOut=${item.timedOut}`,
      item.error ? `error=${item.error}` : "",
      "## stdout",
      item.stdout,
      "## stderr",
      item.stderr,
      "",
    ].join("\n"),
  );
  return fileName;
}

function buildCommands(options = {}) {
  const commands = [{ label: "smoke", args: ["run", "smoke"], timeoutMs: options.timeoutMs || DEFAULT_TIMEOUT_MS }];
  if (options.includeServerTest) {
    commands.push({ label: "server test", args: ["run", "server:test"], timeoutMs: options.timeoutMs || DEFAULT_TIMEOUT_MS });
  }
  if (options.includeWebLint) {
    commands.push({ label: "frontend lint", args: ["--prefix", "dashboard/dashboard-web", "run", "lint"], timeoutMs: options.timeoutMs || DEFAULT_TIMEOUT_MS });
  }
  if (options.includeDockerConfig) {
    commands.push({ label: "docker compose config", command: "docker", args: ["compose", "config", "--quiet"], timeoutMs: options.timeoutMs || DEFAULT_TIMEOUT_MS });
  }
  return commands;
}

function runCommandSpec(spec) {
  if (!spec.command || spec.command === npmCommand) return runCommand(spec.label, spec.args, spec.timeoutMs);
  const startedAt = new Date();
  const result = spawnSync(spec.command, spec.args, {
    cwd: root,
    encoding: "utf8",
    shell: process.platform === "win32",
    timeout: spec.timeoutMs || DEFAULT_TIMEOUT_MS,
  });
  const timedOut = result.error?.code === "ETIMEDOUT";
  return {
    label: spec.label,
    command: [spec.command, ...spec.args].join(" "),
    startedAt: startedAt.toISOString(),
    finishedAt: new Date().toISOString(),
    exitCode: timedOut ? 124 : result.status ?? (result.error ? 1 : 0),
    timeoutMs: spec.timeoutMs || DEFAULT_TIMEOUT_MS,
    timedOut,
    stdout: result.stdout || "",
    stderr: result.stderr || "",
    error: result.error?.message || null,
  };
}

function buildMarkdown(manifest) {
  return [
    "# Local Verification Evidence",
    "",
    `- Status: ${manifest.status}`,
    `- Generated at: ${manifest.generatedAt}`,
    `- Generated by: ${manifest.generatedBy}`,
    `- Site name: ${manifest.siteName}`,
    `- Host name: ${manifest.hostName}`,
    `- Git commit: ${manifest.git.commit}`,
    `- Git branch: ${manifest.git.branch}`,
    `- Git upstream: ${manifest.git.upstream || "missing"}`,
    `- Git pushed to origin/dev: ${manifest.git.pushed ? "yes" : "no"}`,
    `- Working tree clean: ${manifest.git.clean ? "yes" : "no"}`,
    `- Passed command count: ${manifest.passedCommandCount}`,
    `- Failed command count: ${manifest.failedCommandCount}`,
    "",
    "## Commands",
    "",
    "| Status | Command | Log |",
    "| --- | --- | --- |",
    ...manifest.commands.map((item) => `| ${item.exitCode === 0 ? "PASS" : "FAIL"} | \`${item.command}\` | \`${item.logFile}\` |`),
    "",
    "## Notes",
    "",
    "- This evidence proves local contract checks ran on this workstation; it does not replace field runtime, hardware TCP ACK, external CI, or reviewer-signed evidence.",
    "- Attach this with final handover evidence when local smoke verification is part of the delivery review.",
    "",
  ].join("\n");
}

function buildManifest({ generatedBy, siteName, commands }) {
  const failed = commands.filter((item) => item.exitCode !== 0);
  return {
    generatedAt: new Date().toISOString(),
    generatedBy,
    siteName,
    hostName: os.hostname(),
    git: buildGitState(),
    status: failed.length > 0 ? "REVIEW" : "PASS",
    passedCommandCount: commands.length - failed.length,
    failedCommandCount: failed.length,
    commands,
    guardrails: [
      "Local verification evidence does not close field evidence gates by itself.",
      "External CI dispatch remains gated by the approved closeout window.",
      "Real control-board TCP ACK, LiDAR PC payload, and signed manual evidence remain field-owned.",
    ],
  };
}

function writeEvidence(manifest, outputDir) {
  ensureDir(outputDir);
  fs.writeFileSync(path.join(outputDir, "manifest.json"), JSON.stringify(manifest, null, 2));
  fs.writeFileSync(path.join(outputDir, "manifest.md"), buildMarkdown(manifest));
}

function main() {
  const outputRoot = argValue("output-root", "artifacts/local-verification");
  const outputDir = path.join(root, outputRoot, timestampForPath());
  ensureDir(outputDir);
  const timeoutMs = Number(argValue("timeout-ms", DEFAULT_TIMEOUT_MS));
  const specs = buildCommands({
    timeoutMs,
    includeServerTest: hasFlag("include-server-test"),
    includeWebLint: hasFlag("include-web-lint"),
    includeDockerConfig: hasFlag("include-docker-config"),
  });
  const commands = specs.map(runCommandSpec).map((item) => ({
    ...item,
    logFile: writeCommandLog(outputDir, item),
    stdout: undefined,
    stderr: undefined,
  }));
  const manifest = buildManifest({
    generatedBy: argValue("generated-by", process.env.USERNAME || process.env.USER || "Codex"),
    siteName: argValue("site-name", "local-dev-review"),
    commands,
  });
  writeEvidence(manifest, outputDir);
  console.log(`local verification evidence written to ${path.relative(root, outputDir)}`);
  console.log(`local verification status: ${manifest.status}`);
  if (manifest.failedCommandCount > 0) process.exit(1);
}

if (require.main === module) main();

module.exports = {
  buildCommands,
  buildManifest,
  buildMarkdown,
};
