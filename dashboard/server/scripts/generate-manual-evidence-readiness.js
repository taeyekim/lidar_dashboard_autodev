const fs = require("fs");
const os = require("os");
const path = require("path");
const { spawnSync } = require("child_process");

const { timestampForPath } = require("./generate-delivery-evidence");
const { isPlaceholderFieldText } = require("./generate-final-status-report");
const { manualEvidenceRefs } = require("./manual-evidence");

const root = path.join(__dirname, "..", "..", "..");

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function argValue(name, fallback) {
  const prefix = `--${name}=`;
  const match = process.argv.find((arg) => arg.startsWith(prefix));
  return match ? match.slice(prefix.length) : fallback;
}

function gitValue(args) {
  const result = spawnSync("git", args, {
    cwd: root,
    encoding: "utf8",
    shell: process.platform === "win32",
  });
  return result.stdout.trim();
}

function fileExists(relativePath) {
  return fs.existsSync(path.join(root, relativePath));
}

function readTemplateSignals(relativePath) {
  const absolutePath = path.join(root, relativePath);
  if (!fs.existsSync(absolutePath)) {
    return {
      exists: false,
      todoCount: null,
      requiredHeaderCount: 0,
    };
  }
  const content = fs.readFileSync(absolutePath, "utf8");
  return {
    exists: true,
    todoCount: (content.match(/\|\s*TODO\s*\|/g) || []).length,
    requiredHeaderCount: (content.match(/^##\s+/gm) || []).length,
  };
}

function statusForRefs(refs) {
  if (refs.every((item) => item.status === "PRESENT")) return "READY";
  if (refs.some((item) => item.status === "INVALID")) return "REVIEW";
  return "MISSING";
}

function metadataReviewItems(generatedBy, siteName) {
  return [
    isPlaceholderFieldText(generatedBy) ? "Generated-by reviewer metadata is missing or placeholder." : "",
    isPlaceholderFieldText(siteName) ? "Site name metadata is missing or placeholder." : "",
  ].filter(Boolean);
}

function buildManualEvidenceReadiness(input = {}) {
  const refs = input.manualEvidence || manualEvidenceRefs();
  const generatedBy = input.generatedBy || process.env.USERNAME || process.env.USER || "Codex";
  const siteName = input.siteName || "unspecified";
  const items = refs.map((item) => {
    const templateSignals = readTemplateSignals(item.template);
    return {
      type: item.type,
      status: item.status,
      required: Boolean(item.required),
      targetPath: item.path,
      targetExists: fileExists(item.path),
      templatePath: item.template,
      templateExists: templateSignals.exists,
      templateTodoCount: templateSignals.todoCount,
      templateHeaderCount: templateSignals.requiredHeaderCount,
      validationReason: item.validationReason || "",
      nextAction: item.nextAction,
      doneWhen: item.doneWhen,
    };
  });
  const metadataReview = metadataReviewItems(generatedBy, siteName);
  const evidenceStatus = statusForRefs(items);
  const status = metadataReview.length > 0 ? "REVIEW" : evidenceStatus;

  return {
    generatedAt: input.generatedAt || new Date().toISOString(),
    generatedBy,
    siteName,
    hostName: input.hostName || os.hostname(),
    git: input.git || {
      branch: gitValue(["rev-parse", "--abbrev-ref", "HEAD"]),
      commit: gitValue(["rev-parse", "HEAD"]),
      clean: gitValue(["status", "--short"]) === "",
    },
    status,
    readyForFinalClose: metadataReview.length === 0 && items.every((item) => item.status === "PRESENT"),
    missingCount: items.filter((item) => item.status === "MISSING").length,
    invalidCount: items.filter((item) => item.status === "INVALID").length,
    presentCount: items.filter((item) => item.status === "PRESENT").length,
    metadataReview,
    items,
  };
}

function markdownCell(value) {
  return String(value ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

function buildMarkdown(manifest) {
  return [
    "# Manual Evidence Readiness",
    "",
    `- Status: ${manifest.status}`,
    `- Ready for final close: ${manifest.readyForFinalClose}`,
    `- Generated at: ${manifest.generatedAt}`,
    `- Generated by: ${manifest.generatedBy}`,
    `- Site name: ${manifest.siteName}`,
    `- Host name: ${manifest.hostName}`,
    `- Git commit: ${manifest.git.commit}`,
    `- Git branch: ${manifest.git.branch}`,
    `- Working tree clean: ${manifest.git.clean ? "yes" : "no"}`,
    `- Present: ${manifest.presentCount}`,
    `- Missing: ${manifest.missingCount}`,
    `- Invalid: ${manifest.invalidCount}`,
    `- Metadata review items: ${manifest.metadataReview?.length || 0}`,
    "",
    "## Evidence Items",
    "",
    "| Type | Status | Target | Template | Template TODOs | Validation | Next Action | Done When |",
    "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ...manifest.items.map(
      (item) =>
        `| ${markdownCell(item.type)} | ${markdownCell(item.status)} | \`${markdownCell(item.targetPath)}\` | \`${markdownCell(item.templatePath)}\` | ${markdownCell(item.templateTodoCount)} | ${markdownCell(item.validationReason || "ok")} | ${markdownCell(item.nextAction)} | ${markdownCell(item.doneWhen)} |`,
    ),
    "",
    "## Final Close Guardrail",
    "",
    "- This report never substitutes for reviewer evidence.",
    "- Final status remains blocked until every required item is `PRESENT`, generated-by/site-name are concrete field values, and `readyForFinalClose=true`.",
    ...(manifest.metadataReview?.length
      ? ["", "## Metadata Review", "", ...manifest.metadataReview.map((item) => `- ${item}`)]
      : []),
    "",
  ].join("\n");
}

function main() {
  const outputRoot = argValue("output-root", "artifacts/manual-evidence-readiness");
  const outputDir = path.join(root, outputRoot, timestampForPath());
  const manifest = buildManualEvidenceReadiness({
    generatedBy: argValue("generated-by", process.env.USERNAME || process.env.USER || "Codex"),
    siteName: argValue("site-name", "unspecified"),
  });

  ensureDir(outputDir);
  fs.writeFileSync(path.join(outputDir, "manifest.json"), JSON.stringify(manifest, null, 2));
  fs.writeFileSync(path.join(outputDir, "manifest.md"), buildMarkdown(manifest));
  console.log(`manual evidence readiness written to ${path.relative(root, outputDir)}`);
  console.log(`manual evidence readiness status: ${manifest.status}`);
  if (!manifest.readyForFinalClose) {
    console.log(`manual evidence missing=${manifest.missingCount} invalid=${manifest.invalidCount}`);
  }
}

if (require.main === module) {
  main();
}

module.exports = {
  buildManualEvidenceReadiness,
  buildMarkdown,
  metadataReviewItems,
};
